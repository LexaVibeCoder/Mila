import asyncio
from pytdbot import Client, types
from config import settings
from core.context.buffer import (
    push_summary, get_context_within_token_limit,
    peek_oldest_messages_by_tokens, delete_messages_by_ids,
    get_total_entries, get_total_message_tokens
)
from core.llm.embeddings import EmbeddingClient
from core.memory.vector import VectorMemory
from core.pipeline import ThinkPipeline
from core.llm.client import LLMClient
from core.sleep.manager import (
    recover_from_crash,
    start_auto_sleep_scheduler
)
from core.queue import MessageCoordinate
from core.tg_adapter import is_private_chat
from core.tg_auth import register_auth_handlers


class MilaUserbot:
    def __init__(self):
        self.app = Client(
            api_id=settings.API_ID,
            api_hash=settings.API_HASH,
            files_directory=settings.TD_FILES_DIRECTORY,
            database_encryption_key=settings.TD_DATABASE_ENCRYPTION_KEY,
            device_model=settings.DEVICE_MODEL,
            use_message_database=True,
            use_chat_info_database=True,
            use_file_database=True,
            td_verbosity=settings.TD_VERBOSITY,
            user_bot=True,
        )
        self.emb = EmbeddingClient()
        self.text_memory = VectorMemory(settings.FAISS_TEXT_PATH, dim=settings.EMBED_DIM)
        self.pipeline = None
        self.me = None
        # Cheap summarizer for daytime context compression
        self.summarizer_llm = None  # lazy init
        # Per-chat batching / debounce coordinator
        self.messages = MessageCoordinate(self)
        self._ready = asyncio.Event()
        self._periodic_save_task: asyncio.Task | None = None
        self._heartbeat_task: asyncio.Task | None = None

        register_auth_handlers(self.app, phone_hint=settings.PHONE_NUMBER or "")

        @self.app.on_updateAuthorizationState()
        async def _mark_ready(c: Client, update: types.UpdateAuthorizationState):
            if isinstance(
                update.authorization_state, types.AuthorizationStateReady
            ):
                self._ready.set()

        @self.app.on_message()
        async def _on_td_message(c: Client, message: types.Message):
            # Skip our own outgoing messages to avoid self-loops.
            if message.is_outgoing:
                return
            # v1 presence model: every private message is a notification
            # (text / photo / voice / ...). Classification happens in
            # queue.handle() → tg_adapter.normalize_event(); nothing is
            # dropped here except non-private chats.
            if not await is_private_chat(c, message.chat_id):
                return
            await self.handle_text_message(c, message)

        # Peer typing (updateChatAction): if the human is typing, the
        # batcher stops generation and waits for their message.
        # Decorator name is auto-generated by pytdbot, so fall back to
        # add_handler("updateChatAction") if it ever changes.
        async def _on_chat_action(c: Client, update):
            try:
                my_id = None
                if self.me is not None:
                    my_id = getattr(self.me, "id", None)
                await self.messages.handle_typing_update(c, update, my_id=my_id)
            except Exception:
                pass

        try:
            decorator = getattr(self.app, "on_updateChatAction", None)
            if callable(decorator):
                decorator()(_on_chat_action)
            else:
                self.app.add_handler("updateChatAction", _on_chat_action)
        except Exception:
            try:
                self.app.add_handler("updateChatAction", _on_chat_action)
            except Exception:
                pass

    async def start(self):
        # Crash recovery: check if previous sleep was interrupted
        await recover_from_crash()

        await self.app.start(wait_login=False)
        try:
            await asyncio.wait_for(self._ready.wait(), timeout=300)
        except asyncio.TimeoutError:
            raise RuntimeError(
                "TDLib login timed out. Run 'python create_session.py' once "
                "to authorize, then restart."
            )
        self.me = await self.app.getMe()
        if isinstance(self.me, types.Error):
            raise RuntimeError(f"TDLib getMe failed: {self.me.message}")
        username = ""
        if self.me.usernames and self.me.usernames.editable_username:
            username = f" (@{self.me.usernames.editable_username})"
        print(f"Bot started as {self.me.first_name}{username}")

        # Initialize pipeline after getting bot identity
        self.pipeline = ThinkPipeline(
            text_memory=self.text_memory,
            embedding_client=self.emb,
            user_id="system",
            chat_id="system",
            my_user_id=str(self.me.id)
        )

        if settings.TD_DATABASE_ENCRYPTION_KEY == "mila-tdlib-key-change-me":
            print(
                "[Security] WARNING: using default TD_DATABASE_ENCRYPTION_KEY. "
                "Set a unique value in .env (existing data/tdlib was encrypted "
                "with the current key — change it only with a fresh data dir)."
            )

        self._periodic_save_task = asyncio.create_task(self.periodic_save())
        self._heartbeat_task = asyncio.create_task(self._heartbeat_loop())

        # Start auto-sleep scheduler
        start_auto_sleep_scheduler()

    async def _heartbeat_loop(self):
        """Fresh data/bot_heartbeat = healthy for compose healthcheck."""
        import os
        import time
        try:
            while True:
                try:
                    os.makedirs("data", exist_ok=True)
                    with open("data/bot_heartbeat", "w", encoding="utf-8") as f:
                        f.write(str(time.time()))
                except Exception:
                    pass
                await asyncio.sleep(30)
        except asyncio.CancelledError:
            pass

    async def periodic_save(self):
        try:
            while True:
                await asyncio.sleep(settings.FAISS_SAVE_INTERVAL_MIN * 60)
                try:
                    self.text_memory.save()
                except Exception as e:
                    print(f"[Periodic Save Error] {e}")
        except asyncio.CancelledError:
            pass

    async def _ensure_summarizer(self):
        """Lazy init of cheap summarizer LLM for daytime context compression."""
        if self.summarizer_llm is None:
            self.summarizer_llm = LLMClient(
                model=settings.MAIN_LLM_MODEL,  # Use same model but with summarization prompt
                api_base=settings.LLM_API_BASE,
                api_key=settings.LLM_API_KEY
            )

    async def _compress_context(self, chat_id: str):
        """
        If context buffer has too many message tokens, compress the oldest ones into a summary.
        Called BEFORE each new message processing to keep context within limits.

        Uses token-based counting: only message-type entries count toward the limit.
        Summaries are excluded from the limit (they're already compressed).
        """
        total_message_tokens = get_total_message_tokens(chat_id)
        max_tokens = settings.CONTEXT_MAX_TOKENS
        chunk_tokens = settings.CONTEXT_SUMMARIZE_CHUNK_TOKENS

        if total_message_tokens <= max_tokens:
            return  # No compression needed

        # Peek (no deletion yet) — originals are removed only after the
        # LLM summary succeeds. A failed summarization keeps history intact
        # and retries on the next message instead of losing ~chunk_tokens.
        oldest_messages = peek_oldest_messages_by_tokens(chat_id, chunk_tokens)
        if not oldest_messages:
            return

        # Format them for summarization
        texts_to_summarize = "\n".join(
            f"[{m.get('created_at', '')[:10]}] {m['content'][:500]}"
            for m in oldest_messages
            if (m.get('content') or '').strip()
        )

        if not texts_to_summarize.strip():
            return

        # Generate summary using cheap LLM
        await self._ensure_summarizer()
        try:
            summary_prompt = (
                "Summarize the following conversation into a brief summary (2-3 sentences). "
                "Only include facts: what was discussed, key topics. "
                "Do not add interpretations.\n\n"
                f"{texts_to_summarize}"
            )
            response = await self.summarizer_llm.generate(
                messages=[{"role": "user", "content": summary_prompt}],
                max_tokens=300,
                temperature=0.3,
            )
            summary_text = (response.get("thoughts", "") or "").strip()
        except Exception as e:
            print(f"[Context Compression Error] {e} — keeping original messages")
            return

        if not summary_text:
            print("[Context Compression] empty summary — keeping original messages")
            return

        # Push the summary FIRST, then delete originals: a crash in between
        # duplicates context (safe) instead of losing it.
        try:
            push_summary(chat_id, summary_text)
        except Exception as e:
            print(f"[Context Compression Error] push_summary failed: {e}")
            return
        try:
            delete_messages_by_ids(chat_id, [m["id"] for m in oldest_messages])
        except Exception as e:
            print(f"[Context Compression Error] delete failed after summary: {e}")
            return

        # Log token-based stats
        remaining_tokens = get_total_message_tokens(chat_id)
        print(f"[Context Compressed] {len(oldest_messages)} messages (~{chunk_tokens} tokens) → summary. "
              f"Message tokens remaining: {remaining_tokens}/{max_tokens}. "
              f"Total entries: {get_total_entries(chat_id)}.")

    def _build_histories(self, chat_id: str) -> tuple[list[dict], list[dict]]:
        """
        Build two separate histories from the CONTEXT BUFFER (not raw chunks):

        1. user_visible_history — only messages that were actually sent to Telegram
        2. agent_internal_history — IDENTICAL to user_visible_history

        The context buffer contains only messages that are part of the active
        context window, plus summaries of older conversation segments.

        Uses token-based limit: only messages within CONTEXT_MAX_TOKENS are included.
        Summaries are always included (they're already compressed).

        Silent (unsent) assistant entries (content="") are SKIPPED entirely.
        """
        context_entries = get_context_within_token_limit(chat_id, settings.CONTEXT_MAX_TOKENS)

        user_visible = []
        agent_internal = []

        for entry in context_entries:
            content_raw = entry.get("content", "") or ""
            ts = entry.get("created_at", "")
            time_prefix = ""
            if ts and entry["type"] != "summary":
                time_prefix = f"[{ts}] "

            if entry["type"] == "summary":
                # Summary entries are injected as a system-like context block
                summary_block = f"[Summary previous conversation:]\n{content_raw}"
                user_visible.append({
                    "role": "system",
                    "content": summary_block
                })
                agent_internal.append({
                    "role": "system",
                    "content": summary_block
                })
            else:
                user_visible.append({
                    "role": "assistant" if entry.get("role") == "assistant" else "user",
                    "content": f"{time_prefix}{content_raw}"
                })
                agent_internal.append({
                    "role": "assistant" if entry.get("role") == "assistant" else "user",
                    "content": f"{time_prefix}{content_raw}"
                })

        return user_visible, agent_internal

    def _resolve_roles_in_histories(self, histories: list[dict], chat_id: str) -> list[dict]:
        """
        Roles are now stored directly in the context buffer, so histories are
        already correctly attributed. Kept as a pass-through for callers.
        """
        return histories

    async def handle_text_message(self, client: Client, message: types.Message):
        """Thin delegator — the batching/processing lives in self.messages."""
        await self.messages.handle(client, message)

    async def stop(self):
        for attr in ("_periodic_save_task", "_heartbeat_task"):
            task = getattr(self, attr, None)
            if task is not None:
                task.cancel()
                try:
                    await task
                except asyncio.CancelledError:
                    pass
                setattr(self, attr, None)
        # Cancel per-chat workers so docker stop doesn't strand a turn mid-LLM.
        try:
            tasks = list(getattr(self.messages, "_tasks", {}).values())
            for t in tasks:
                try:
                    t.cancel()
                except Exception:
                    pass
            for t in tasks:
                try:
                    await t
                except (asyncio.CancelledError, Exception):
                    pass
        except Exception:
            pass
        # Stop auto-sleep scheduler.
        try:
            from core.sleep.manager import _auto_sleep_task
            if _auto_sleep_task is not None and not _auto_sleep_task.done():
                _auto_sleep_task.cancel()
        except Exception:
            pass
        try:
            self.text_memory.save()
        except Exception as e:
            print(f"[Stop Save Error] {e}")
        await self.app.stop()
